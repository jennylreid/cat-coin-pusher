"""CP-74: embeds Codex's approved Hug art (work/cp74-art/revision2, revision 2) in the game as WebP data URIs -> cp74-art.js.
Same canvases (shoulder 800x640, arms 800x2080), same pixels re-encoded as WebP q95 (alpha lossless) to fit the update size.
Usage: python gen-art.py"""
from pathlib import Path
from PIL import Image
import io,base64,hashlib,json
p=Path(__file__).parent;A=p.parents[1]/'cp74-art'/'revision2'
SRC={'shoulder':'hug-shoulder-v2-800x640.png','left':'hug-left-arm-v2-800x2080.png','right':'hug-right-arm-v2-800x2080.png'}
out=['// CP-74 Hug art (Codex revision 2, work/cp74-art/revision2): fixed canvases, WebP data URIs. Generated by gen-art.py; do not edit.','const CP74_ART={']
meta={}
for k,f in SRC.items():
    raw=(A/f).read_bytes();im=Image.open(io.BytesIO(raw));assert im.mode=='RGBA'
    b=io.BytesIO();im.save(b,'WEBP',quality=95,method=6,alpha_quality=100);w=b.getvalue()
    meta[k]={'source':f,'sourceSHA256':hashlib.sha256(raw).hexdigest(),'size':im.size,'webpBytes':len(w)}
    out.append(" %s:'data:image/webp;base64,%s',"%(k,base64.b64encode(w).decode()))
out.append('};')
(p/'cp74-art.js').write_text('\n'.join(out)+'\n',encoding='utf-8');(p/'cp74-art.json').write_text(json.dumps(meta,indent=1));print(json.dumps(meta))
